import { test } from 'node:test';
import assert from 'node:assert/strict';
import { generate, tsType } from '../scripts/generate.mjs';

test('tsType maps JSON schema to TypeScript', () => {
  assert.equal(tsType({ type: 'string' }), 'string');
  assert.equal(tsType({ type: 'integer' }), 'number');
  assert.equal(tsType({ type: 'string', format: 'uuid' }), 'string');
  assert.equal(tsType({ type: 'string', nullable: true }), 'string | null');
  assert.equal(tsType({ type: 'array', items: { $ref: '#/components/schemas/Cart' } }), 'Cart[]');
  assert.equal(tsType({ type: 'array', items: { type: 'string', nullable: true } }), '(string | null)[]');
  assert.equal(tsType({ type: 'string', enum: ['card', 'wallet'] }), '"card" | "wallet"');
  assert.equal(tsType({ allOf: [{ $ref: '#/components/schemas/A' }, { type: 'object', required: ['x'], properties: { x: { type: 'integer' } } }] }, true), 'A & { x: number }');
  assert.equal(tsType({ type: 'object', required: ['a'], properties: { a: { type: 'string' }, b: { type: 'integer' } } }, true), '{ a: string; b?: number }');
  assert.equal(tsType(undefined), 'unknown');
});

const out = generate(['orders', 'payments', 'cart-api']);

test('every schema becomes a type and every JSON operation a method named by its operationId', () => {
  for (const name of ['OrderSummary', 'Order', 'OrderStatus', 'Payment', 'Cart', 'CartLine']) assert.match(out, new RegExp(`export (interface|type) ${name}\\b`));
  for (const op of ['listOrders', 'getOrder', 'cancelOrder', 'createCharge', 'getPayment', 'createRefund', 'getCart', 'addCartItem', 'applyCoupon', 'checkoutCart']) assert.match(out, new RegExp(`\\n    ${op}: \\(`));
  assert.match(out, /export function createClient\(request: Request\)/);
  assert.match(out, /export type Client = ReturnType<typeof createClient>;/);
});

test('required and optional fields, nullable values and the extra-property rule come through', () => {
  assert.match(out, /export interface OrderSummary \{[^}]*\n  cartId: string;/s);
  assert.match(out, /export interface Cart \{[^}]*\n  coupon: string \| null;/s);
  assert.match(out, /export type Order = OrderSummary & \{/);
  assert.match(out, /unitPrice\?: number \| null;/);
});

test('paths, verbs and bodies are built correctly', () => {
  assert.match(out, /getOrder: \(id: string, init\?: RequestInit\) => request<Order>\(`\/orders\/\$\{encodeURIComponent\(id\)\}`, init\)/);
  assert.match(out, /createCharge: \(body: \{ orderId: string; method: "card" \| "wallet" \}, init\?: RequestInit\) => request<Payment>\('\/payments\/charges', \{ \.\.\.init, method: 'POST', body: JSON\.stringify\(body\) \}\)/);
  assert.match(out, /removeCartItem: \(productId: string, init\?: RequestInit\) => request<Cart>\(`\/cart\/items\/\$\{encodeURIComponent\(productId\)\}`, \{ \.\.\.init, method: 'DELETE' \}\)/);
  assert.match(out, /checkoutCart: \(init\?: RequestInit\) => request<\{ cartId: string \}>\('\/cart\/checkout'/);
  assert.match(out, /cancelOrder: \(id: string, body\?: \{ reason\?: string \}/); // an optional body stays optional
});

test('query parameters become an optional object and are skipped when undefined', () => {
  const all = generate(['catalog-api', 'invoices']);
  assert.match(all, /listProducts: \(query\?: \{ category\?: string; page\?: number \}, init\?: RequestInit\) => request<Product\[\]>\(`\/products\$\{qs\(query\)\}`, init\)/);
  assert.match(all, /getProduct: \(id: string,/);
});

test('operations that do not return JSON are left out of the client', () => {
  const all = generate(['invoices']);
  assert.doesNotMatch(all, /getInvoicePdf/);
  assert.match(all, /getInvoiceForOrder/);
});

test('the output is deterministic, names the contracts version and services, and an unknown service is an error', () => {
  assert.equal(generate(['orders']), generate(['orders']));
  assert.match(out, /^\/\/ Generated by shoplab-contracts scripts\/generate\.mjs \(contracts \d+\.\d+\.\d+; services: orders, payments, cart-api\)\. Do not edit: regenerate\./);
  assert.throws(() => generate(['ghost']), /unknown service "ghost"/);
});
